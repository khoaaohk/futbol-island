#!/usr/bin/env node
/*
 * Learning analytics (Oct 9 2026): generates the FIXED allowlist of lesson / question / option ids that a beat's counter
 * channel may carry, straight from the real lesson content (public/lessons/<format>.json).
 *   node scripts/gen-learning-ids.cjs          writes the two generated modules
 *   node scripts/gen-learning-ids.cjs --check  exits 1 when they are out of date (tests/admin-analytics-learning.cjs runs it)
 *
 * Two outputs, so the every-page tracker bundle stays small:
 *  - lib/analytics/learningIds.generated.ts   lesson id + options per question (≈3 KB), imported by the tracker and the server;
 *  - lib/analytics/learningText.generated.ts  lesson names, question and option text and the correct option, SERVER ONLY
 *    (lib/analytics/report.ts puts the text beside the counts on /admin). The browser only ever sends indices.
 * Re-run it whenever lessons are added, removed or re-ordered (a removed id is then dropped by the server, never an error).
 */
'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const FORMATS=['7v7','9v9','11v11','futsal'];
const ids=[],text=[];
for(const f of FORMATS){
 const lessons=JSON.parse(fs.readFileSync(path.join(ROOT,'public/lessons',f+'.json'),'utf8'));
 for(const l of lessons){
  if(!/^[A-Za-z0-9_]{1,40}$/.test(l.id))throw Error('lesson id not allowlist-safe: '+l.id);
  if(l.questions.length>9)throw Error(l.id+': more than 9 questions (ids use one digit)');
  for(const q of l.questions)if(q.options.length<1||q.options.length>9)throw Error(l.id+': 1-9 options per question');
  ids.push([f,l.id,l.questions.map(q=>q.options.length).join('')]);
  text.push([f,l.id,l.name,l.questions.map(q=>[q.q,q.options,q.correct])]);
 }
}
const seen=new Set();for(const [,id] of ids){if(seen.has(id))throw Error('duplicate lesson id across formats: '+id);seen.add(id);}
const head=`// GENERATED by scripts/gen-learning-ids.cjs from public/lessons/*.json. Do not edit; re-run the script.\n`;
const idsSrc=head+`/** [format, lesson id, options per question (one digit per question, in order)]. */\n`+
 `export const LESSON_TABLE:readonly (readonly ['7v7'|'9v9'|'11v11'|'futsal',string,string])[]=${JSON.stringify(ids)};\n`;
const textSrc=head+`/** SERVER ONLY (lib/analytics/report.ts): [format, lesson id, lesson name, [question, options, correct option][]]. */\n`+
 `export const LESSON_TEXT:readonly (readonly [string,string,string,readonly (readonly [string,readonly string[],number])[]])[]=${JSON.stringify(text)};\n`;
const out=[['lib/analytics/learningIds.generated.ts',idsSrc],['lib/analytics/learningText.generated.ts',textSrc]];
if(process.argv.includes('--check')){
 const stale=out.filter(([f,src])=>!fs.existsSync(path.join(ROOT,f))||fs.readFileSync(path.join(ROOT,f),'utf8')!==src).map(([f])=>f);
 if(stale.length){console.error('out of date (run node scripts/gen-learning-ids.cjs): '+stale.join(', '));process.exit(1);}
 console.log('learning ids up to date');
}else{
 for(const [f,src] of out)fs.writeFileSync(path.join(ROOT,f),src);
 console.log(`wrote ${ids.length} lessons, ${ids.reduce((n,[, ,o])=>n+o.length,0)} questions`);
}
