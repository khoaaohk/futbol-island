#!/usr/bin/env node
// Counter introduction dates (Nov 6 2026, the daily data layer lib/analytics/daily.ts): walks the git history of
// lib/analytics/countIds.ts, evaluates FIXED_COUNT_IDS at every commit (with the files it imports at that same commit) and
// writes the Pacific day each id first appeared to lib/analytics/countSince.generated.ts. Ids that exist only in the working
// tree (not committed yet) get today's Pacific day. Re-run after adding counters:  node scripts/gen-count-since.cjs
// The daily layer treats days before an id's date as "not tracked" (null), unless real data for it arrived earlier.
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),cp=require('child_process');
const ROOT=path.resolve(__dirname,'..');
const ts=require(path.join(ROOT,'node_modules/typescript'));
const git=(...a)=>cp.execFileSync('git',a,{cwd:ROOT,encoding:'utf8',maxBuffer:64<<20,stdio:['ignore','pipe','ignore']});
const pacificDay=ms=>new Intl.DateTimeFormat('en-CA',{timeZone:'America/Los_Angeles',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(ms));

/** Evaluates lib/analytics/countIds.ts as of `rev` (null = the working tree) and returns FIXED_COUNT_IDS. */
function idsAt(rev){
 const cache=new Map();
 const readAt=rel=>{if(rev===null){const f=path.join(ROOT,rel);return fs.existsSync(f)?fs.readFileSync(f,'utf8'):null;}
  try{return git('show',`${rev}:${rel}`);}catch{return null;}};
 const resolve=(fromRel,id)=>{const base=path.posix.normalize(id.startsWith('@/')?id.slice(2):path.posix.join(path.posix.dirname(fromRel),id));
  for(const f of [base,base+'.ts',base+'.tsx',base+'.json'])if(readAt(f)!==null)return f;throw Error(`cannot resolve ${id} from ${fromRel} at ${rev}`);};
 const load=rel=>{if(cache.has(rel))return cache.get(rel);const src=readAt(rel);
  if(rel.endsWith('.json')){const v={default:JSON.parse(src)};cache.set(rel,v);return v;}
  const m={exports:{}};cache.set(rel,m.exports);
  vm.runInNewContext(ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,
   {module:m,exports:m.exports,require:id=>id.startsWith('.')||id.startsWith('@/')?load(resolve(rel,id)):require(id),process:{env:{}},console,Intl,Date,Math,JSON});
  cache.set(rel,m.exports);return m.exports;};
 return load('lib/analytics/countIds.ts').FIXED_COUNT_IDS||[];
}

const commits=git('log','--reverse','--format=%H %ct','--','lib/analytics/countIds.ts').trim().split('\n').filter(Boolean).map(l=>{const [h,t]=l.split(' ');return {h,day:pacificDay(Number(t)*1000)};});
const first=new Map();
for(const c of commits){let ids;try{ids=idsAt(c.h);}catch(e){console.warn('skip',c.h.slice(0,8),String(e.message).slice(0,80));continue;}
 for(const id of ids)if(!first.has(id))first.set(id,c.day);}
// Stable across re-runs: an id already in the generated file keeps its earlier day (an uncommitted id must not move to a
// later "today" each time this runs before the commit lands).
const OUT_FILE=path.join(ROOT,'lib/analytics/countSince.generated.ts');
if(fs.existsSync(OUT_FILE))for(const m of fs.readFileSync(OUT_FILE,'utf8').matchAll(/^ '(\d{4}-\d\d-\d\d)':(\[.*\]),$/gm))
 for(const id of JSON.parse(m[2]))if(!first.has(id)||m[1]<first.get(id))first.set(id,m[1]);
const today=pacificDay(Date.now());let uncommitted=0;
for(const id of idsAt(null))if(!first.has(id)){first.set(id,today);uncommitted++;}
const current=new Set(idsAt(null));
const byDay=new Map();for(const [id,d] of first)if(current.has(id)){if(!byDay.has(d))byDay.set(d,[]);byDay.get(d).push(id);}
const days=[...byDay.keys()].sort();
const out=`/**
 * GENERATED by scripts/gen-count-since.cjs from the git history of lib/analytics/countIds.ts (do not edit by hand; re-run it
 * after adding counters). For each Pacific day, the FIXED_COUNT_IDS that first appeared in a commit that day. Ids not yet
 * committed when this was generated carry the generation day (${today}).
 * Used by lib/analytics/daily.ts for each counter's \`trackedSince\`.
 */
export const COUNT_SINCE_GENERATED='${today}';
export const COUNT_SINCE:Record<string,readonly string[]>={
${days.map(d=>` '${d}':${JSON.stringify(byDay.get(d).sort())},`).join('\n')}
};
`;
fs.writeFileSync(path.join(ROOT,'lib/analytics/countSince.generated.ts'),out);
console.log(`${current.size} ids over ${days.length} days (${uncommitted} uncommitted → ${today}); wrote lib/analytics/countSince.generated.ts`);
