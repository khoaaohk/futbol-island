   if(tau>T_OR+.3&&tau<T_CR-.3)pose=blendPose(pose,dribble(distOf(k,tau)/2.2,{foot:'l',speed:.6}),sm(T_OR+.3,T_OR+.55,tau)*(1-sm(T_CR-.9,T_CR-.7,tau)));
   const wl=sm(T_CR-.95,T_CR-.75,tau)*(1-sm(T_CR-.6,T_CR-.45,tau));if(wl>0)pose=blendPose(pose,LOOKUP,wl);
   const u=tau-T_CR,ws=sm(-.62,-.45,u)*(1-sm(.4,.75,u));if(ws>0){pose=blendPose(pose,strike(clamp(STRIKE_CONTACT+u/SD_O),{foot:'l',power:.85}),ws);yaw=lerpAng(yaw,CR_YAW,ws);}
