  const u=clamp(T/T_CH),bu=u*(1.08-.08*u),perp:[number,number]=[S_H[1],-S_H[0]],mid:[number,number]=[(LB[0]+CH[0])/2+perp[0]*3.2,(LB[1]+CH[2])/2+perp[1]*3.2];
